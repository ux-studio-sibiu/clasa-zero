// Regenerates app/components/pattern-background/data/*.ts: the svg backgrounds, palettes and pattern
// tiles from effects-collection/randomize-studio (which stays their editable source), and the jpg list
// from this project's public/images/backgrounds.
//
//   node scripts/generate-pattern-data.mjs [path/to/randomize-studio]
//
// The 87 pattern tiles are baked into overlay-patterns.ts as markup, the way the 43 backgrounds
// already are, so the panel's grid and the live layer need no requests and no public/ folder.

import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1"));
const SRC = path.resolve(process.argv[2] || path.join(here, "../../effects-collection/randomize-studio"));
const OUT = path.join(here, "../app/components/pattern-background/data");
const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8");
const header = (from) => `// Generated by scripts/generate-pattern-data.mjs from effects-collection/randomize-studio/${from}. Do not hand-edit.\n\n`;
const windowGlobal = (file, key) => { const w = {}; new Function("window", read(file))(w); return w[key]; };

/* ---- the 43 svg backgrounds ---- */
const backgrounds = windowGlobal("js/svg-backgrounds-data.js", "BACKGROUNDS");
fs.writeFileSync(path.join(OUT, "svg-backgrounds.ts"), header("js/svg-backgrounds-data.js (svgbackgrounds.com free set)") +
  `export type SvgBackground = { id: string; name: string; tags: string; css: Record<string, string> };\n\n` +
  `export const SVG_BACKGROUNDS: SvgBackground[] = [\n` + backgrounds.map((b) => "  " + JSON.stringify({ id: b.id, name: b.name, tags: b.tags, css: b.css })).join(",\n") + `\n];\n`);

/* ---- the 300 palettes ---- */
const palettes = windowGlobal("js/palettes.js", "PALETTES");
fs.writeFileSync(path.join(OUT, "palettes.ts"), header("js/palettes.js (Adobe Color community themes)") +
  `export type Palette = { id: number; name: string; by: string; colors: string[]; topics: string[] };\n\n` +
  `export const PALETTES: Palette[] = [\n` + palettes.map((p) => "  " + JSON.stringify({ id: p.id, name: p.name, by: p.by, colors: p.colors, topics: p.topics })).join(",\n") + `\n];\n`);

/* ---- the 87 pattern tiles, sizes from the catalogue and markup from the folder ---- */
const catalogue = new Function(read("js/overlay-patterns.js") + "; return OVERLAY_PATTERNS;")();
const tiles = catalogue.map(({ n, w, h }) => {
  // One line, no comments or XML prolog. No tile carries a "#" (all fill="currentColor") and none
  // needs its internal ids namespaced, since each stays its own document.
  const svg = read(`overlay-patterns/${n}.svg`).replace(/<\?xml[^>]*>/, "").replace(/<!--[\s\S]*?-->/g, "").replace(/\s*\n\s*/g, " ").trim();
  return `  { name: ${JSON.stringify(n)}, w: ${w}, h: ${h}, svg: ${JSON.stringify(svg)} }`;
});
fs.writeFileSync(path.join(OUT, "overlay-patterns.ts"), header("js/overlay-patterns.js + overlay-patterns/*.svg (hero patterns)") +
  `// Used as MASKS, so only their alpha matters and the colour comes from CSS.\n` +
  `export type OverlayPattern = { name: string; w: number; h: number; svg: string };\n\n` +
  `export const OVERLAY_PATTERNS: OverlayPattern[] = [\n` + tiles.join(",\n") + `\n];\n`);

/* ---- the jpg backgrounds, from this project's own public folder ---- */
// The image layer's catalogue: the panel's grid, the random roll and the template validator all read it.
// Re-run after adding or removing a jpg.
const JPG_DIR = path.join(here, "../public/images/backgrounds");
const images = fs.readdirSync(JPG_DIR).filter((f) => f.endsWith(".jpg")).map((f) => f.slice(0, -4))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
fs.writeFileSync(path.join(OUT, "image-backgrounds.ts"), `// Generated by scripts/generate-pattern-data.mjs from public/images/backgrounds. Do not hand-edit.

` +
  `export const IMAGE_BACKGROUNDS: string[] = ${JSON.stringify(images)};
`);

console.log(`${backgrounds.length} backgrounds, ${palettes.length} palettes, ${tiles.length} patterns, ${images.length} images -> ${path.relative(process.cwd(), OUT)}`);
